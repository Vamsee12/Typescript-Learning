let a:number = 20, b:number = 10;

//1.Addition
let sum = a + b;
console.log("Sum: ", sum);

//2.Subtraction
let difference = a - b;
console.log("Difference: ", difference);

//3.Multiplication
let product = a * b;
console.log("Product: ", product);      

//4.Division
let quotient = a / b;
console.log("Quotient: ", quotient);            

//5.Modulus
let remainder = a % b;
console.log("Remainder: ", remainder);

//6.Exponentiation
let power = 5 ** 2;    //Five_Square = 5*5 = 25
console.log("Power: ", power);