//Logical Operators
//Returns boolean - true/false
//&& - Logical AND operator
//|| - Logical OR operator
//! - Logical NOT operator 

let m:boolean = true;
let n:boolean = false;

//Logical AND operator
console.log(m && n); // false
//Logical OR operator
console.log(m || n);
//Logical NOT operator
console.log(!m); // false  - here m is true as we put !m it returns true and vice versa
console.log(!n); // true